struct Rgb8 {
  uint8_t r,g,b;
  Rgb8(uint8_t rr=0,uint8_t gg=0,uint8_t bb=0):r(rr),g(gg),b(bb){}
};

enum Scene : uint8_t {
  COURSE_FLOW=0,
  FIELD_MIX=1,
  SIGNATURE=2,
  QUIET_COSMOS=3
};

// Local manual/automatic presentation state. AUTO resolves to one of the five
// manual Vibes and never changes the user's independent Motion control.
enum Vibe : uint8_t { VIBE_CHILL=0, VIBE_GROOVE=1, VIBE_HEAVY=2,
                      VIBE_PSYCHEDELIC=3, VIBE_COSMIC=4, VIBE_AUTO=5 };

struct VibeAxes {
  uint8_t structure=0,flow=0,depth=0,symmetry=0,detail=0;
  uint8_t paletteMotion=0,density=0,negativeSpace=0,transitionEnergy=0;
};

struct Controls {
  // Literal semantic controls. No categorical remapping.
  uint8_t audioResponse=50; // 0 = no audio modulation, 50 = 1.0x, 100 = 2.0x
  uint8_t motion=50;        // 0 = 0.5x, 50 = 1.0x, 100 = 1.5x
  uint8_t matrixBrightness=24; // independent Matrix pixel scale; WLED master is transport-fixed at 255
  uint8_t auxBrightness=24; // independent scale before native DDP output
  Scene scene=COURSE_FLOW;
  Vibe vibe=VIBE_CHILL;
};

struct VisualVariant {
  uint8_t kernel=0; // index into the proven 28-effect ANIMartRIX selection
  uint8_t family=0;
  uint8_t palette=1;
  uint8_t speed=128;
  uint8_t profile=96;
  uint8_t style=176;
  uint8_t amount=224;
  int8_t hueOffset=0;
  uint8_t transform=0;
  uint8_t warp=0;
  uint16_t salt=0;
  uint16_t dwellSeconds=14;
  uint32_t signature=0;
};

struct AudioFrame {
  AudioFrame(uint8_t b=0,uint8_t m=0,uint8_t t=0,uint8_t v=0,bool p=false)
    :bass(b),mid(m),treble(t),volume(v),peak(p){}
  // Inputs are the already-processed WLED AudioReactive values.
  uint8_t bass=0;
  uint8_t mid=0;
  uint8_t treble=0;
  uint8_t volume=0;
  bool peak=false;
  uint8_t bassBody=0,midBody=0,trebleBody=0;
  uint8_t bassPulse=0,midPulse=0,treblePulse=0;
  uint8_t energy=0;
  uint8_t lowEnergy=0,midEnergy=0,highEnergy=0,transient=0,slowEnergy=0;
};

struct CanonicalFrame {
  uint32_t frame=0;
  uint32_t phaseQ16=0;
  Controls controls{};
  AudioFrame audio{};
  VisualVariant variant{};
  VisualVariant previousVariant{};
  uint8_t variantMix=255;
  Vibe vibe=VIBE_CHILL;
  VibeAxes vibeAxes{};
  Rgb8 palette[4]{};
  Rgb8 previousPalette[4]{};
};

struct FieldCoords {
  uint16_t nx=0;
  uint16_t ny=0;
  uint16_t z=0;
  uint16_t paletteDrift=0;
};

inline uint16_t audioGainQ8(uint8_t response){
  // Linear response depth: 0,25,50,75,100 map to 0,0.5,1,1.5,2x.
  // Keep the zero path exact and avoid the quadratic control's near-dead lower half.
  const uint32_t v=response>100u?100u:response;
  return (uint16_t)((v*512u+50u)/100u);
}

inline uint16_t motionQ8(uint8_t motion){
  // Broad, monotonic time range: nearly-drifting at 0, natural at 50,
  // decisively fast at 100. This controls the shared animation clock only.
  if(motion<=50u) return (uint16_t)(1u + ((uint32_t)motion*255u+25u)/50u);
  return (uint16_t)(256u + ((uint32_t)(motion-50u)*768u+25u)/50u);
}

inline uint32_t advancePhaseQ16(uint32_t phaseQ16,uint32_t dtMs,uint8_t motion){
  // At Motion=50, advance 8 Q16 units/ms (~8.19 s per low-16-bit traversal).
  // Motion is applied here and nowhere else.
  const uint16_t rate=motionQ8(motion);
  return phaseQ16 + (uint32_t)(((uint64_t)dtMs * 8u * rate) >> 8);
}

inline FieldCoords fieldCoords(uint16_t x,uint16_t y,uint16_t scale,uint32_t phaseQ16){
  // The old renderer used only the low 16 bits of phase, which made the base
  // field repeat exactly after ~8.2 s at Motion=50. Preserve smooth low-word
  // travel while letting the high-word epoch slowly drift the sampled field.
  // Both Matrix and AUX consume these exact coordinates, so coherence remains
  // single-frame/single-brain while the short exact loop is eliminated.
  const uint16_t epoch=(uint16_t)(phaseQ16>>16);
  FieldCoords c;
  c.nx=(uint16_t)((uint32_t)x*scale + 0x1357u + (uint32_t)epoch*17u);
  c.ny=(uint16_t)((uint32_t)y*scale + 0x2468u + (uint32_t)epoch*29u);
  c.z=(uint16_t)phaseQ16;
  c.paletteDrift=(uint16_t)((uint32_t)epoch*73u);
  return c;
}

inline uint8_t unitAudio8(float v){
  if(v<=0.0f) return 0;
  if(v>=1.0f) return 255;
  return (uint8_t)(v*255.0f+0.5f);
}

inline AudioFrame audioFromVibe(float bassPulse,float midPulse,float treblePulse,
                                float bassAtt,float midAtt,float trebleAtt,float energy,
                                uint8_t volume,bool peak){
  AudioFrame a{};
  a.bassPulse=unitAudio8(bassPulse); a.midPulse=unitAudio8(midPulse); a.treblePulse=unitAudio8(treblePulse);
  // AI: below section was generated by an AI
  // The adaptive envelopes are normalized around 1.0 during ordinary music.
  // Map that center into a useful, smooth body signal while silence still fades to zero.
  a.bassBody=unitAudio8((bassAtt-0.68f)/0.55f);
  a.midBody=unitAudio8((midAtt-0.68f)/0.55f);
  a.trebleBody=unitAudio8((trebleAtt-0.68f)/0.55f);
  a.bass=a.bassPulse; a.mid=a.midPulse; a.treble=a.treblePulse;
  a.energy=unitAudio8(energy*1.35f); a.volume=volume; a.peak=peak;
  // AI: end
  return a;
}

inline uint8_t scaleAudio(uint8_t v,uint8_t response){
  const uint32_t x=(uint32_t)v*audioGainQ8(response);
  const uint32_t y=(x+128u)>>8;
  return (uint8_t)(y>255u?255u:y);
}

inline uint8_t scale8(uint8_t v,uint8_t gain){
  return (uint8_t)(((uint16_t)v*(uint16_t)gain+127u)/255u);
}

inline Rgb8 scaleRgb(Rgb8 c,uint8_t gain){
  return {scale8(c.r,gain),scale8(c.g,gain),scale8(c.b,gain)};
}

inline Rgb8 scaleRgbQ8(Rgb8 c,uint16_t gainQ8){
  auto channel=[gainQ8](uint8_t v){const uint32_t x=(uint32_t)v*gainQ8+128u;const uint32_t y=x>>8;return (uint8_t)(y>255u?255u:y);};
  return {channel(c.r),channel(c.g),channel(c.b)};
}

inline uint16_t auxAudioRestoreQ8(const CanonicalFrame& frame){
  const AudioFrame& a=frame.audio;
  uint8_t activity=a.energy;
  if(a.lowEnergy>activity)activity=a.lowEnergy;
  if(a.midEnergy>activity)activity=a.midEnergy;
  if(a.highEnergy>activity)activity=a.highEnergy;
  if(a.transient>activity)activity=a.transient;
  const uint32_t response=frame.controls.audioResponse>100u?100u:frame.controls.audioResponse;
  const uint32_t extra=(response*26u*activity+12750u)/25500u;
  return (uint16_t)(256u+extra); // at most +10.16%, audio-energy gated
}

inline uint8_t blend8(uint8_t a,uint8_t b,uint8_t mix){
  return (uint8_t)(((uint16_t)a*(255u-mix)+(uint16_t)b*mix+127u)/255u);
}

inline uint8_t tri8(uint8_t x){ return x<128u?(uint8_t)(x*2u):(uint8_t)(255u-(x-128u)*2u); }

inline Rgb8 hueRotate(Rgb8 c,uint8_t shift){
  const uint8_t mx=c.r>c.g?(c.r>c.b?c.r:c.b):(c.g>c.b?c.g:c.b);
  const uint8_t mn=c.r<c.g?(c.r<c.b?c.r:c.b):(c.g<c.b?c.g:c.b);
  const uint8_t delta=(uint8_t)(mx-mn);
  if(!delta || !mx) return c;
  int16_t hue;
  if(mx==c.r) hue=(int16_t)(43*((int)c.g-(int)c.b)/(int)delta);
  else if(mx==c.g) hue=(int16_t)(85+43*((int)c.b-(int)c.r)/(int)delta);
  else hue=(int16_t)(171+43*((int)c.r-(int)c.g)/(int)delta);
  const uint8_t h=(uint8_t)(hue+shift);
  const uint8_t s=(uint8_t)(((uint16_t)delta*255u)/mx), region=h/43u, rem=(uint8_t)((h-region*43u)*6u);
  const uint8_t p=(uint8_t)(((uint16_t)mx*(255u-s))/255u);
  const uint8_t q=(uint8_t)(((uint16_t)mx*(255u-(((uint16_t)s*rem)/255u)))/255u);
  const uint8_t t=(uint8_t)(((uint16_t)mx*(255u-(((uint16_t)s*(255u-rem))/255u)))/255u);
  switch(region){ case 0:return {mx,t,p}; case 1:return {q,mx,p}; case 2:return {p,mx,t}; case 3:return {p,q,mx}; case 4:return {t,p,mx}; default:return {mx,p,q}; }
}

inline Rgb8 blend(Rgb8 a,Rgb8 b,uint8_t mix){
  return {blend8(a.r,b.r,mix),blend8(a.g,b.g,mix),blend8(a.b,b.b,mix)};
}

inline Rgb8 paletteAtColors(const Rgb8 palette[4],uint16_t posQ16){
  const uint8_t slot=(uint8_t)(posQ16>>14); // 0..3
  const uint8_t next=(uint8_t)((slot+1u)&3u);
  const uint8_t frac=(uint8_t)((posQ16>>6)&255u);
  return blend(palette[slot],palette[next],frac);
}

inline Rgb8 paletteAt(const CanonicalFrame& f,uint16_t posQ16){
  return paletteAtColors(f.palette,posQ16);
}

inline void defaultPalette(Scene s,Rgb8 out[4]){
  switch(s){
    case FIELD_MIX:
      out[0]=Rgb8(255,54,28); out[1]=Rgb8(255,190,28); out[2]=Rgb8(26,230,170); out[3]=Rgb8(30,120,255); break;
    case SIGNATURE:
      out[0]=Rgb8(255,40,160); out[1]=Rgb8(130,50,255); out[2]=Rgb8(35,220,255); out[3]=Rgb8(255,180,35); break;
    case QUIET_COSMOS:
      out[0]=Rgb8(20,30,90); out[1]=Rgb8(65,40,150); out[2]=Rgb8(20,130,170); out[3]=Rgb8(120,65,180); break;
    default:
      out[0]=Rgb8(20,210,170); out[1]=Rgb8(40,110,255); out[2]=Rgb8(180,55,255); out[3]=Rgb8(255,95,80); break;
  }
}

inline CanonicalFrame makeFrame(uint32_t frame,uint32_t phaseQ16,const Controls& c,const AudioFrame& a,const VisualVariant& variant=VisualVariant{},const VisualVariant& previous=VisualVariant{},uint8_t mix=255){
  CanonicalFrame f;
  f.frame=frame; f.phaseQ16=phaseQ16; f.variant=variant; f.previousVariant=previous; f.variantMix=mix;
  f.controls=c; f.audio=a; defaultPalette(c.scene,f.palette);
  const uint8_t hue=(uint8_t)(variant.palette*37u+variant.salt%31u);
  for(Rgb8& color:f.palette) color=hueRotate(color,hue);
  defaultPalette(c.scene,f.previousPalette);
  const uint8_t oldHue=(uint8_t)(previous.palette*37u+previous.salt%31u);
  for(Rgb8& color:f.previousPalette) color=hueRotate(color,oldHue);
  return f;
}

inline Rgb8 applyAudio(const CanonicalFrame& f,Rgb8 src,uint8_t position){
  if(src.r==0 && src.g==0 && src.b==0) return src;
  // Source-coupled lanes use Vibe16 pulse + continuous envelopes. One shared
  // response budget keeps simultaneous bands expressive without stacking.
  uint8_t bands[3]={
    scaleAudio(f.audio.bass>f.audio.bassBody?f.audio.bass:f.audio.bassBody,f.controls.audioResponse),
    scaleAudio(f.audio.mid>f.audio.midBody?f.audio.mid:f.audio.midBody,f.controls.audioResponse),
    scaleAudio(f.audio.treble>f.audio.trebleBody?f.audio.treble:f.audio.trebleBody,f.controls.audioResponse)
  };
  const uint16_t sum=(uint16_t)bands[0]+bands[1]+bands[2];
  if(!sum) return src;
  const uint8_t budget=bands[0]>bands[1]?(bands[0]>bands[2]?bands[0]:bands[2]):(bands[1]>bands[2]?bands[1]:bands[2]);
  const uint8_t bass=(uint8_t)(((uint16_t)budget*bands[0])/sum);
  const uint8_t mid=(uint8_t)(((uint16_t)budget*bands[1])/sum);
  const uint8_t high=(uint8_t)(((uint16_t)budget*bands[2])/sum);

  // bass: luminance/body
  const uint8_t bassMix=(uint8_t)(((uint16_t)bass*88u)>>8);
  src.r=(uint8_t)(src.r + (((255u-src.r)*bassMix)>>8));
  src.g=(uint8_t)(src.g + (((255u-src.g)*bassMix)>>8));
  src.b=(uint8_t)(src.b + (((255u-src.b)*bassMix)>>8));

  // mids: palette morph; never invent a separate palette
  const uint8_t midMix=(uint8_t)(((uint16_t)mid*144u)>>8);
  if(midMix){
    const Rgb8 target=f.palette[(position+1u)&3u];
    src=blend(src,target,midMix);
  }

  // highs: crisp local accent, bounded and deterministic
  if(high && (((uint16_t)position*37u + (uint16_t)(f.frame&255u)*11u + (uint16_t)f.variant.salt)&255u) < (high>>1)){
    const uint8_t lift=(uint8_t)(((uint16_t)high*64u)>>8);
    src=blend(src,Rgb8(255,255,255),lift);
  }
  return src;
}

inline void perimeterCoord22(uint8_t index,uint16_t& x,uint16_t& y){
  const uint8_t i=(uint8_t)(index%22u);
  if(i<5u){
    x=0; y=(uint16_t)(((uint32_t)i*15u)/4u);
  } else if(i<11u){
    const uint8_t j=(uint8_t)(i-5u);
    x=(uint16_t)(((uint32_t)j*31u)/5u); y=0;
  } else if(i<16u){
    const uint8_t j=(uint8_t)(i-11u);
    x=31; y=(uint16_t)(15u-((uint32_t)j*15u)/4u);
  } else {
    const uint8_t j=(uint8_t)(i-16u);
    x=(uint16_t)(31u-((uint32_t)j*31u)/5u); y=15;
  }
}

template <typename Sampler>
inline void renderCompanion22(const CanonicalFrame& frame, Sampler sample, Rgb8 out[22]) {
  const uint16_t audioRestore=auxAudioRestoreQ8(frame);
  for (uint8_t i=0; i<22; ++i) {
    uint16_t x=0, y=0;
    perimeterCoord22(i,x,y);
    out[i]=scaleRgbQ8(scaleRgb(sample(frame,x,y),frame.controls.auxBrightness),audioRestore);
  }
}

inline void transformPoint(const CanonicalFrame& f,uint16_t x,uint16_t y,uint16_t w,uint16_t h,uint16_t& tx,uint16_t& ty){
  tx=x; ty=y; const uint8_t t=f.variant.transform;
  if(t&1u) tx=(uint16_t)(w-1u-tx);
  if(t&2u) ty=(uint16_t)(h-1u-ty);
  if(t&4u){ const uint16_t sx=(uint16_t)((f.variant.salt%w)); tx=(uint16_t)((tx+sx)%w); ty=(uint16_t)((ty+(f.variant.salt>>5)%h)%h); }
  switch(f.variant.warp&7u){
    case 1: tx=(uint16_t)((tx+(ty*3u+f.variant.salt)%w)%w); break;
    case 2: ty=(uint16_t)((ty+(tx*2u+(f.variant.salt>>4))%h)%h); break;
    case 3: tx=(uint16_t)((tx+(ty*ty+f.variant.salt)%w)%w); break;
    case 4: ty=(uint16_t)((ty+(tx*tx+(f.variant.salt>>3))%h)%h); break;
    case 5: tx=(uint16_t)((tx+(ty*5u+tx*2u+f.variant.salt)%w)%w); break;
    case 6: ty=(uint16_t)((ty+(tx*3u+ty*2u+(f.variant.salt>>2))%h)%h); break;
    case 7: { const uint16_t ox=tx; tx=(uint16_t)((tx+(ty*3u+f.variant.salt)%w)%w); ty=(uint16_t)((ty+(ox*2u+(f.variant.salt>>4))%h)%h); break; }
    default: break;
  }
}

inline uint8_t proceduralKernel(uint8_t kernel,uint8_t n1,uint8_t n2,uint8_t geom,uint8_t wave,uint8_t phase){
  switch(kernel%28u){
    case 0:return n1; case 1:return n2; case 2:return blend8(n1,n2,96);
    case 3:return blend8(n1,n2,192); case 4:return (uint8_t)(255u-(n1>n2?n1-n2:n2-n1));
    case 5:return blend8(geom,n1,112); case 6:return blend8(geom,n2,176);
    case 7:return (uint8_t)(((uint16_t)n1+n2+geom)/3u);
    case 8:return (uint8_t)(((uint16_t)(255u-n1)+n2)/2u);
    case 9:return (uint8_t)(((uint16_t)n1+(255u-n2))/2u);
    case 10:return blend8(wave,n1,144); case 11:return blend8(wave,n2,144);
    case 12:return blend8((uint8_t)(255u-geom),n1,128);
    case 13:return blend8(geom,n1,(uint8_t)(wave>>1));
    case 14:return blend8(geom,n2,(uint8_t)(255u-(wave>>1)));
    case 15:return (uint8_t)((n1+n2+phase)/3u);
    case 16:return (uint8_t)((n1*3u+n2)/4u); case 17:return (uint8_t)((n1+n2*3u)/4u);
    case 18:return blend8((uint8_t)(geom^wave),n1,112);
    case 19:return blend8((uint8_t)(geom+phase),n2,160);
    case 20:return blend8((uint8_t)(wave+phase),n1,176);
    case 21:return blend8((uint8_t)(255u-wave),n2,176);
    case 22:return blend8((uint8_t)(geom+n1/2u),n2,128);
    case 23:return blend8((uint8_t)(geom+n2/2u),n1,128);
    case 24:return (uint8_t)(((uint16_t)tri8((uint8_t)(n1+phase))+n2)/2u);
    case 25:return (uint8_t)(((uint16_t)tri8((uint8_t)(n2+phase))+n1)/2u);
    case 26:return blend8(wave,(uint8_t)(n1^n2),128);
    default:return blend8((uint8_t)(geom^phase),(uint8_t)(n1+n2),128);
  }
}

inline Rgb8 composeFieldColor(const CanonicalFrame& f,uint8_t n1,uint8_t n2,uint8_t geom,
                               uint8_t wave,uint8_t phase,uint16_t x,uint16_t y){
  const uint8_t field=proceduralKernel(f.variant.kernel,n1,n2,geom,wave,phase);
  const uint16_t palettePos=(uint16_t)(((uint16_t)field<<8)+((uint16_t)n2<<3)+wave+f.variant.salt+((uint32_t)f.variant.kernel*0x311u));
  Rgb8 color=paletteAt(f,palettePos);
  color=applyAudio(f,color,(uint8_t)((field+(x*3u+y*5u))>>6));
  return color;
}

inline uint8_t audioBand(const CanonicalFrame& f,uint8_t pulse,uint8_t body){
  return scaleAudio(pulse>body?pulse:body,f.controls.audioResponse);
}

inline float clamp01(float x){ return x<0.0f?0.0f:(x>1.0f?1.0f:x); }

inline float smoothstep01(float x){ x=clamp01(x); return x*x*(3.0f-2.0f*x); }

// Composition coverage is separate from the generative color field. Pixels
// outside the selected objects are exact RGB black, giving every scene real
// negative space. Audio changes object size/shape, never a whole-frame lift.
inline float foundationCoverage(const CanonicalFrame& f,uint16_t x,uint16_t y,uint16_t w,uint16_t h,const VisualVariant& v){
  if(!w||!h) return 0.0f;
  const float tau=6.28318530718f;
  const float t=(float)f.phaseQ16*(tau/65536.0f)+(float)(v.salt&4095u)*(tau/4096.0f);
  const float u=((float)x/(float)(w>1?w-1:1))*2.0f-1.0f;
  const float q=((float)y/(float)(h>1?h-1:1))*2.0f-1.0f;
  const float bass=(float)audioBand(f,f.audio.bassPulse,f.audio.bassBody)/255.0f;
  const float mids=(float)audioBand(f,f.audio.midPulse,f.audio.midBody)/255.0f;
  const uint8_t k=v.kernel;
  float d=0.0f, width=0.0f;
  switch(f.controls.scene){
    case COURSE_FLOW: {
      // Two directional, curved lanes. Curated kernel groups alter flow path.
      const float bend=(k%7u<3u?0.16f:0.27f);
      const float lane=q+0.34f*sinf(u*3.0f+t*0.20f)+bend*sinf(u*1.5f-t*0.12f);
      const float spacing=(k%3u==0u?0.78f:1.02f);
      d=fabsf(sinf((lane*spacing+u*0.10f)*tau+t*0.09f));
      width=0.48f+bass*0.15f+mids*0.07f;
      break;
    }
    case FIELD_MIX: {
      // A few independently drifting, overlapping soft-edged islands.
      float best=0.0f;
      const uint8_t count=(uint8_t)(2u+(k%3u));
      for(uint8_t i=0;i<count;++i){
        const float a=t*(0.07f+0.015f*(float)i)+(float)(v.salt+i*97u)*0.013f;
        const float cx=0.56f*cosf(a+(float)i*2.1f);
        const float cy=0.48f*sinf(a*0.83f+(float)i*1.7f);
        const float dx=(u-cx)*(1.0f+0.2f*sinf(a));
        const float dy=(q-cy)*(1.0f+0.2f*cosf(a*0.7f));
        const float radius=sqrtf(dx*dx+dy*dy);
        const float blob=1.0f-smoothstep01((radius-(0.24f+bass*0.10f+mids*0.07f))/0.18f);
        if(blob>best) best=blob;
      }
      return best;
    }
    case SIGNATURE: {
      // Intentional orbital/radial motifs with a broken arc, not a filled disk.
      const float radius=sqrtf(u*u+q*q);
      const float angle=atan2f(q,u);
      const float lobes=0.76f+0.24f*cosf(angle*(float)(3u+k%5u)+t*0.12f);
      const float ring=fabsf(radius-(0.52f+0.12f*sinf(angle*2.0f-t*0.14f)));
      const float arcGap=(cosf(angle*2.0f+t*0.08f)>-0.66f)?1.0f:0.0f;
      d=ring*lobes;
      width=0.16f+bass*0.09f+mids*0.04f;
      return arcGap*smoothstep01((width+0.09f-d)/0.09f);
    }
    case QUIET_COSMOS: {
      // Sparse moving nebula wisps plus a deterministic pinprick star field.
      const float cloud=sinf(u*2.6f+q*1.1f+t*0.07f)*sinf(q*3.1f-u*0.7f-t*0.05f);
      const float cloudMask=smoothstep01((cloud-(0.34f-bass*0.12f-mids*0.08f))/0.24f)*0.30f;
      const uint32_t cell=(uint32_t)x*0x9e3779b9u ^ (uint32_t)y*0x85ebca6bu ^ (uint32_t)(v.salt+1u)*0xc2b2ae35u;
      const bool star=(cell%23u)==0u;
      const float twinkle=star?(0.32f+0.68f*(0.5f+0.5f*sinf(t*0.13f+(float)(cell&1023u)*0.0061f))):0.0f;
      return cloudMask>twinkle*0.72f?cloudMask:twinkle*0.72f;
    }
    default: break;
  }
  return smoothstep01((width+0.12f-d)/0.12f);
}

// The four user scenes are macro-domains. Each has a distinct base composition;
// every domain is further composed with the donor's 28-kernel generative space.
inline float foundationFieldVariant(const CanonicalFrame& f,uint16_t x,uint16_t y,uint16_t w,uint16_t h,const VisualVariant& v){
  if(!w||!h) return 0.0f;
  const float tau=6.28318530718f;
  const float phaseOffset=(float)(v.salt&4095u)*(tau/4096.0f);
  const float t=(float)f.phaseQ16*(tau/65536.0f)+phaseOffset;
  float u=((float)x/(float)(w>1?w-1:1))*2.0f-1.0f;
  float yv=((float)y/(float)(h>1?h-1:1))*2.0f-1.0f;
  if(v.transform&1u)u=-u;
  if(v.transform&2u)yv=-yv;
  if(v.transform&4u){const float old=u;u=-yv;yv=old;}
  const uint8_t bass=audioBand(f,f.audio.bassPulse,f.audio.bassBody);
  const uint8_t mids=audioBand(f,f.audio.midPulse,f.audio.midBody);
  const uint8_t treble=audioBand(f,f.audio.treblePulse,f.audio.trebleBody);
  const float b=(float)bass/255.0f,m=(float)mids/255.0f,hi=(float)treble/255.0f;
  const float expansion=1.0f+b*0.34f*sinf(t*0.42f);
  u*=expansion; yv*=expansion;
  const float warpX=sinf(yv*4.2f+t*0.31f)*m*0.24f;
  const float warpY=sinf(u*3.7f-t*0.27f)*m*0.20f;
  u+=warpX; yv+=warpY;
  switch(v.warp&7u){
    case 1:u+=sinf(yv*3.4f+t*0.17f)*0.22f;break;
    case 2:yv+=sinf(u*3.1f-t*0.19f)*0.20f;break;
    case 3:u+=sinf(yv*2.0f)*0.14f;yv+=sinf(u*2.3f+t*0.13f)*0.14f;break;
    case 4:u+=sinf(yv*5.0f+t*0.11f)*0.10f;break;
    case 5:yv+=sinf(u*4.8f-t*0.12f)*0.10f;break;
    case 6:u+=sinf(yv*2.5f+t*0.2f)*0.17f;yv+=sinf(u*2.5f-t*0.2f)*0.17f;break;
    case 7:{const float old=u;u+=sinf(yv*3.3f+t*0.1f)*0.12f;yv+=sinf(old*3.3f-t*0.1f)*0.12f;break;}
    default:break;
  }

  const float radius=sqrtf(u*u+yv*yv);
  const float angle=atan2f(yv,u);
  float base=0.5f;
  switch(f.controls.scene){
    case FIELD_MIX: {
      const float a=sinf((u*2.2f+yv*0.52f)*tau+t*0.62f);
      const float c=sinf((yv*2.0f-u*0.44f)*tau-t*0.47f);
      base=0.5f+0.5f*a*c; break;
    }
    case SIGNATURE: {
      const float rings=sinf(radius*8.5f-t*0.72f);
      const float lobes=sinf(u*3.1f+t*0.23f)*sinf(yv*3.1f-t*0.19f);
      base=0.5f+0.33f*rings+0.17f*lobes; break;
    }
    case QUIET_COSMOS: {
      const float nebula=sinf(u*2.0f+yv*1.1f+t*0.14f)*sinf(yv*2.7f-u*0.7f-t*0.11f);
      const uint32_t cell=(uint32_t)x*0x9e3779b9u ^ (uint32_t)y*0x85ebca6bu ^ (uint32_t)(v.salt+1u)*0xc2b2ae35u;
      const bool star=(cell%29u)==0u;
      const float twinkle=star?(0.24f+0.76f*(0.5f+0.5f*sinf(t*0.38f+(float)(cell&1023u)*0.0061f))):0.0f;
      base=0.10f+0.14f*nebula+twinkle*0.72f; break;
    }
    default: {
      const float flowA=sinf((u*1.35f+yv*0.63f)*tau-t*0.44f);
      const float flowB=sinf((u*0.55f-yv*0.92f)*tau+t*0.27f);
      base=0.5f+0.31f*flowA+0.19f*flowB; break;
    }
  }

  // Twenty-eight smooth geometry kernels: ribbons, grids, folds, rings,
  // petals, vortices, orbitals, arcs, and travelling contours. Their phase is
  // always derived from the one canonical clock; none is frame-random.
  float k=0.5f;
  switch(v.kernel%28u){
    case 0:k=0.5f+0.5f*sinf((u+yv*0.35f)*tau+t*0.37f);break;
    case 1:k=0.5f+0.5f*sinf((yv*1.5f)*tau-t*0.31f);break;
    case 2:k=0.5f+0.5f*sinf((u*1.5f)*tau+t*0.29f);break;
    case 3:k=0.5f+0.5f*sinf(u*4.3f+t*0.22f)*sinf(yv*4.0f-t*0.19f);break;
    case 4:k=0.5f+0.5f*sinf(radius*9.0f-t*0.41f);break;
    case 5:k=0.5f+0.5f*sinf(sqrtf(u*u*0.48f+yv*yv)*11.0f+t*0.27f);break;
    case 6:k=0.5f+0.5f*sinf((fabsf(u)+fabsf(yv))*7.2f-t*0.33f);break;
    case 7:k=0.5f+0.5f*sinf(radius*6.0f-angle*2.4f+t*0.36f);break;
    case 8:k=0.5f+0.5f*sinf(radius*5.8f+cosf(angle*4.0f)*0.8f-t*0.28f);break;
    case 9:k=0.5f+0.5f*cosf(u*5.1f+t*0.24f)*cosf(yv*5.1f-t*0.21f);break;
    case 10:k=0.5f+0.5f*sinf((yv+u*u*0.52f)*7.0f+t*0.3f);break;
    case 11:k=0.5f+0.5f*sinf((u+yv*yv*0.5f)*7.0f-t*0.28f);break;
    case 12:k=0.5f+0.5f*sinf((u+sinf(yv*3.2f+t*0.16f)*0.38f)*6.4f-t*0.26f);break;
    case 13:k=0.5f+0.5f*sinf((yv+sinf(u*3.4f-t*0.14f)*0.34f)*6.5f+t*0.24f);break;
    case 14:k=0.5f+0.5f*sinf(radius*6.1f+cosf(angle*4.0f)*0.6f-t*0.25f);break;
    case 15:{const float dx=u-0.55f*cosf(t*0.21f),dy=yv-0.52f*sinf(t*0.21f);k=0.5f+0.5f*sinf(sqrtf(dx*dx+dy*dy)*9.0f-t*0.35f);break;}
    case 16:k=0.5f+0.5f*sinf(u*yv*15.0f+t*0.32f);break;
    case 17:k=0.5f+0.5f*sinf(angle*5.0f+radius*3.0f-t*0.27f);break;
    case 18:k=0.5f+0.5f*sinf(fmaxf(fabsf(u),fabsf(yv))*8.5f+t*0.23f);break;
    case 19:k=0.5f+0.5f*sinf(fmaxf(fabsf(u),0.866f*fabsf(yv)+0.5f*fabsf(u))*8.0f-t*0.22f);break;
    case 20:{const float dx=u-0.34f,dy=yv+0.26f;k=0.5f+0.5f*sinf(sqrtf(dx*dx+dy*dy)*10.0f+t*0.26f);break;}
    case 21:k=0.5f+0.5f*sinf((u+yv)*3.4f+t*0.2f)*cosf((u-yv)*3.7f-t*0.24f);break;
    case 22:k=0.5f+0.5f*(sinf(u*4.0f+t*0.2f)+sinf(yv*4.7f-t*0.16f)+sinf((u+yv)*3.6f+t*0.14f))/3.0f;break;
    case 23:k=0.5f+0.5f*sinf((u+0.34f*sinf(yv*3.0f+t*0.17f))*6.0f-t*0.25f);break;
    case 24:k=0.5f+0.5f*sinf(u*6.0f+t*0.22f)*sinf(yv*6.0f-t*0.18f);break;
    case 25:k=0.5f+0.5f*cosf(radius*10.0f+angle*2.0f-t*0.28f);break;
    case 26:k=0.5f+0.5f*sinf((u*1.7f+yv*0.6f+0.22f*sinf(yv*4.0f+t*0.15f))*6.2f-t*0.24f);break;
    default:k=0.5f+0.5f*sinf((yv*1.4f-u*0.8f)*tau+t*0.23f);break;
  }
  const float mix=(f.controls.scene==QUIET_COSMOS)?0.30f:0.46f;
  float field=base*(1.0f-mix)+k*mix;
  field+=hi*0.11f*sinf((u*18.0f+yv*14.0f)*tau+t*1.8f);
  return clamp01(field);
}

inline float foundationFieldValue(const CanonicalFrame& f,uint16_t x,uint16_t y,uint16_t w,uint16_t h){
  const float current=foundationFieldVariant(f,x,y,w,h,f.variant);
  if(f.variantMix==255u) return current;
  const float previous=foundationFieldVariant(f,x,y,w,h,f.previousVariant);
  const float mix=(float)f.variantMix/255.0f;
  return previous*(1.0f-mix)+current*mix;
}

inline Rgb8 renderFoundationPixel(const CanonicalFrame& f,uint16_t x,uint16_t y,uint16_t w,uint16_t h){
  if(!w||!h) return {};
  const float cover=foundationCoverage(f,x,y,w,h,f.variant);
  if(cover<=0.28f) return {};
  const float currentField=foundationFieldVariant(f,x,y,w,h,f.variant);
  Rgb8 color=paletteAt(f,(uint16_t)(currentField*65535.0f+0.5f));
  color=scaleRgb(color,(uint8_t)(cover*255.0f+0.5f));
  if(f.variantMix==255u) return color;
  const float oldCover=foundationCoverage(f,x,y,w,h,f.previousVariant);
  if(oldCover<=0.28f && f.variantMix>=128u) return color;
  const float oldField=foundationFieldVariant(f,x,y,w,h,f.previousVariant);
  Rgb8 oldColor=paletteAtColors(f.previousPalette,(uint16_t)(oldField*65535.0f+0.5f));
  oldColor=scaleRgb(oldColor,(uint8_t)(oldCover*255.0f+0.5f));
  return blend(oldColor,color,f.variantMix);
}

