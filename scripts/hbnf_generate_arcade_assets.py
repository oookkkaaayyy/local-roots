#!/usr/bin/env python3
"""Bundle the existing browser game modules as deterministic PROGMEM assets."""
from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
FIRMWARE = ROOT / "firmware/phase2/integration-r6-f89-compact-font"
SOURCES = [
    ("HBNF_ARCADE_INDEX", FIRMWARE / "arcade-ui/index.html", "HBNFHTML"),
    ("HBNF_ARCADE_APP", FIRMWARE / "arcade-ui/app.mjs", "HBNFJS"),
    ("HBNF_ARCADE_INPUT", ROOT / "hbnf-cart-core/domain/arcade-input.mjs", "HBNFINPUT"),
    ("HBNF_ARCADE_RUNTIME", ROOT / "hbnf-cart-core/domain/arcade-runtime.mjs", "HBNFRUNTIME"),
    ("HBNF_ARCADE_CONTROLLER", ROOT / "hbnf-cart-core/domain/arcade-controller.mjs", "HBNFCONTROLLER"),
    ("HBNF_ARCADE_SNAKE", ROOT / "hbnf-cart-core/domain/snake-runtime.mjs", "HBNFSNAKE"),
    ("HBNF_ARCADE_MAZE", ROOT / "hbnf-cart-core/domain/maze-chase-runtime.mjs", "HBNFMAZE"),
]
OUTPUT = FIRMWARE / "usermod/hbnf_arcade_assets.h"


def render() -> str:
    rows = ["#pragma once", "// Generated by scripts/hbnf_generate_arcade_assets.py; do not edit."]
    for symbol, path, delimiter in SOURCES:
        data = path.read_text(encoding="utf-8")
        if f"){delimiter}\"" in data:
            raise ValueError(f"raw-string delimiter collision in {path}")
        rows.extend([f"static const char {symbol}[] PROGMEM = R\"{delimiter}(", data.rstrip("\n"), f"){delimiter}\";"])
    return "\n".join(rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"stale generated arcade assets: {OUTPUT}", file=sys.stderr)
            return 1
        print("arcade assets match source modules")
        return 0
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as output:
        output.write(expected)
    print(f"generated {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
